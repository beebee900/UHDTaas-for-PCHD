"""Generate lib/src/api/apdt_api.dart from contracts/openapi/apdt.yaml.

    ../../.venv/bin/python tool/gen_api.py           write the client
    ../../.venv/bin/python tool/gen_api.py --check   exit 1 when the client is out of date
"""

from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent.parent
SPEC = HERE.parent.parent / "contracts" / "openapi" / "apdt.yaml"
OUT = HERE / "lib" / "src" / "api" / "apdt_api.dart"
PREFIX = "/v1/t/{tenant_id}"


def camel(text: str) -> str:
    parts = [p for p in re.split(r"[^A-Za-z0-9]+", text) if p]
    return parts[0].lower() + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def method_name(method: str, path: str) -> str:
    static = [s for s in path.removeprefix(PREFIX).split("/") if s and not s.startswith("{")]
    return camel(" ".join([method, *static]) or method)


def dart_path(path: str) -> str:
    return re.sub(r"\{([a-z_]+)\}", lambda m: "$" + camel(m.group(1)), path)


def render(spec: dict) -> str:
    lines = [
        "// Generated by tool/gen_api.py from contracts/openapi/apdt.yaml. Do not edit.",
        "",
        "import 'dart:convert';",
        "",
        "import 'package:http/http.dart' as http;",
        "",
        "/// An RFC 9457 problem returned by the APDT.",
        "class ApiException implements Exception {",
        "  ApiException(this.status, this.problem);",
        "",
        "  final int status;",
        "  final Map<String, dynamic>? problem;",
        "",
        "  String get detail => problem?['detail'] as String? ?? 'HTTP $status';",
        "",
        "  @override",
        "  String toString() => 'ApiException($status): $detail';",
        "}",
        "",
        "/// Client of the APDT Layer 7.4 API (design 03, 3.7).",
        "class ApdtApi {",
        "  ApdtApi(this.baseUrl, {http.Client? client, this.token}) : _client = client ?? http.Client();",
        "",
        "  final String baseUrl;",
        "  final http.Client _client;",
        "  String? token;",
        "",
    ]
    names: set[str] = set()
    for path, ops in sorted(spec["paths"].items()):
        if not path.startswith("/v1/") and path != "/auth/token":
            continue
        for method, op in sorted(ops.items()):
            name = "login" if path == "/auth/token" else method_name(method, path)
            # The item route shares its collection's name: GET /episodes and /episodes/{id}.
            if name in names and path.endswith("}"):
                name += "ById"
            if name in names:
                raise SystemExit(f"duplicate method name {name} for {method} {path}")
            names.add(name)
            params = [p for p in op.get("parameters", []) if p["in"] in ("path", "query")]
            args = [f"required String {camel(p['name'])}" for p in params
                    if p["in"] == "path" or p.get("required")]
            args += [f"String? {camel(p['name'])}" for p in params
                     if p["in"] == "query" and not p.get("required")]
            has_body = "requestBody" in op
            if has_body:
                args.append("required Map<String, dynamic> body")
            query = [p for p in params if p["in"] == "query"]
            summary = op.get("summary") or name
            lines.append(f"  /// {method.upper()} {path}: {summary}.")
            signature = f"{{{', '.join(args)}}}" if args else ""
            lines.append(f"  Future<dynamic> {name}({signature}) => _send(")
            lines.append(f"        '{method.upper()}',")
            lines.append(f"        '{dart_path(path)}',")
            if query:
                entries = ", ".join(f"'{q['name']}': {camel(q['name'])}" for q in query)
                lines.append(f"        query: {{{entries}}},")
            if has_body:
                lines.append("        body: body,")
            lines.append("      );")
            lines.append("")
    lines += [
        "  Future<dynamic> _send(String method, String path,",
        "      {Map<String, String?>? query, Map<String, dynamic>? body}) async {",
        "    final params = {for (final e in (query ?? {}).entries) if (e.value != null) e.key: e.value!};",
        "    final uri = Uri.parse('$baseUrl$path').replace(queryParameters: params.isEmpty ? null : params);",
        "    final request = http.Request(method, uri)",
        "      ..headers['accept'] = 'application/json';",
        "    if (token != null) request.headers['authorization'] = 'Bearer $token';",
        "    if (body != null) {",
        "      request.headers['content-type'] = 'application/json';",
        "      request.body = jsonEncode(body);",
        "    }",
        "    final response = await http.Response.fromStream(await _client.send(request));",
        "    final decoded = response.body.isEmpty ? null : jsonDecode(utf8.decode(response.bodyBytes));",
        "    if (response.statusCode >= 400) {",
        "      throw ApiException(response.statusCode, decoded is Map<String, dynamic> ? decoded : null);",
        "    }",
        "    return decoded;",
        "  }",
        "}",
        "",
    ]
    return "\n".join(lines)


def formatted(text: str) -> str:
    """The client as `dart format` writes it, so the drift check matches the stored file."""
    dart = shutil.which("dart") or str(Path.home() / ".local/share/atra-tools/flutter/bin/dart")
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "apdt_api.dart"
        path.write_text(text, encoding="utf-8")
        subprocess.run([dart, "format", "--page-width", "100", str(path)], check=True,
                       capture_output=True)
        return path.read_text(encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    ns = parser.parse_args()
    text = formatted(render(yaml.safe_load(SPEC.read_text(encoding="utf-8"))))
    if ns.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"out of date: {OUT.relative_to(HERE)}")
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(HERE)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
