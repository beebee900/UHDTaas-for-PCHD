  ///
  /// Additional delegates can be added by appending to this list in
  /// MaterialApp. This list does not have to be used at all if a custom list
  /// of delegates is preferred or required.
  static const List<LocalizationsDelegate<dynamic>> localizationsDelegates =
      <LocalizationsDelegate<dynamic>>[
        delegate,
        GlobalMaterialLocalizations.delegate,
        GlobalCupertinoLocalizations.delegate,
        GlobalWidgetsLocalizations.delegate,
      ];

  /// A list of this localizations delegate's supported locales.
  static const List<Locale> supportedLocales = <Locale>[
    Locale('en'),
    Locale('ha'),
    Locale('ig'),
    Locale('pcm'),
    Locale('yo'),
  ];

  /// No description provided for @appTitlePerson.
  ///
  /// In en, this message translates to:
  /// **'My health twin'**
  String get appTitlePerson;

  /// No description provided for @appTitleCarer.
  ///
  /// In en, this message translates to:
  /// **'Carer'**
  String get appTitleCarer;

  /// No description provided for @appTitlePatient.
  ///
  /// In en, this message translates to:
  /// **'My care'**
  String get appTitlePatient;

  /// No description provided for @appTitleWard.
  ///
  /// In en, this message translates to:
  /// **'Ward'**
  String get appTitleWard;

  /// No description provided for @appTitleChw.
  ///
  /// In en, this message translates to:
  /// **'Community health'**
  String get appTitleChw;

  /// No description provided for @signIn.
  ///
  /// In en, this message translates to:
  /// **'Sign in'**
  String get signIn;

  /// No description provided for @username.
  ///
  /// In en, this message translates to:
  /// **'Username'**
  String get username;

  /// No description provided for @password.
  ///
  /// In en, this message translates to:
  /// **'Password'**
  String get password;

  /// No description provided for @signInFailed.
  ///
  /// In en, this message translates to:
  /// **'The username or password is not correct.'**
  String get signInFailed;

  /// No description provided for @serviceUnreachable.
  ///
  /// In en, this message translates to:
  /// **'The service cannot be reached. Try again when you are online.'**
  String get serviceUnreachable;

  /// No description provided for @signOut.
  ///
  /// In en, this message translates to:
  /// **'Sign out'**
  String get signOut;

  /// No description provided for @dashboard.
  ///
  /// In en, this message translates to:
  /// **'Dashboard'**
  String get dashboard;

  /// No description provided for @signedInAs.
  ///
  /// In en, this message translates to:
  /// **'Signed in as {user} ({role})'**
  String signedInAs(String user, String role);

  /// No description provided for @worklist.
  ///
  /// In en, this message translates to:
  /// **'Worklist'**
  String get worklist;

