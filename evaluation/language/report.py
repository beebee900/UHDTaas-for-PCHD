"""Write the language evaluation report and the Yoruba rating sheet from the VM results.

    python -m evaluation.language.report --src var/wp14d/pulled

Reads `<src>/eval/*.json` and the adapter metrics, writes `evaluation/language/REPORT.md` and
`evaluation/language/yoruba_rating_sheet.csv`. Numbers that are missing are written as
"not run".
"""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path
from typing import Any

from evaluation.language import common

HERE = Path(__file__).resolve().parent
LANG_ROWS = [("yo", "Yoruba"), ("ha", "Hausa"), ("ig", "Igbo"), ("pcm", "Nigerian Pidgin")]
RATING_N = 50


def load(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8")) if path.is_file() else None


def fmt(value: float | None, digits: int = 1) -> str:
    return "not run" if value is None else f"{value:.{digits}f}"


def rating_sheet(items: list[dict[str, Any]], path: Path) -> int:
    rows = items[:RATING_N]
    with path.open("w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["id", "english_source", "yoruba_output", "adequacy_1_to_5",
                    "fluency_1_to_5", "comment"])
        for i, item in enumerate(rows, 1):
            w.writerow([f"{i:02d}", item["english"], item["adapter"], "", "", ""])
    return len(rows)


def build(src: Path) -> str:
    ev = src / "eval"
    bt = load(ev / "backtranslation.json") or {}
    det = load(ev / "detection.json")
    rt = load(ev / "roundtrip.json")
    hosts = load(ev / "hosts.json")
    lines = ["# Language models: evaluation report (WP14d)", "",
             "Generated by `python -m evaluation.language.report`. All scores are on text "
             "that the adapters did not see in training.", "",
             "## LoRA adapters (Qwen2.5-0.5B-Instruct)", "",
             "| Language | Steps | Dev loss | Translation chrF base | Translation chrF adapter "
             "| Dialogue chrF base | Dialogue chrF adapter | Back-translation chrF (adapter / "
             "reference) |", "|---|---|---|---|---|---|---|---|"]
    yo_items: list[dict[str, Any]] = []
    for code, name in LANG_ROWS:
        res = load(ev / f"{code}.json")
        met = load(src / f"lora-{code}" / "metrics.json") or {}
        if not res:
            lines.append(f"| {name} | not run | | | | | | |")
            continue
        t, d = res["translation"], res["dialogue"]
        b = bt.get(code)
        back = f"{b['chrf_adapter']:.1f} / {b['chrf_reference']:.1f}" if b else "not applicable"
        lines.append(f"| {name} | {met.get('steps', '')} | {fmt(met.get('dev_loss'), 3)} "
                     f"| {fmt(t['chrf_base'])} | {fmt(t['chrf_adapter'])} "
                     f"| {fmt(d['chrf_base'])} | {fmt(d['chrf_adapter'])} | {back} |")
        if code == "yo":
            yo_items = d["items"]
    lines += ["", "Translation: English to the language, human references (MENYO-20k test for "
              "Yoruba, MAFAND-MT test for the others), chrF 0 to 100. Dialogue: held-out "
              "template slots; the reference reply is an NLLB-200 translation (Pidgin: the "
              "author's template), so the score measures agreement with that text. "
              "Back-translation: adapter replies translated to English by NLLB-200 and "
              "compared with the English source; the second number is the same round trip for "
              "the reference reply. Pidgin has no NLLB code. The base model is scored on a "
              "smaller subset than the adapter.", ""]
    n = rating_sheet(yo_items, HERE / "yoruba_rating_sheet.csv") if yo_items else 0
    lines += ["## Yoruba human ratings", "",
              f"Pending. `yoruba_rating_sheet.csv` holds {n} adapter outputs with the English "
              "source for a Yoruba-speaking rater to score for adequacy and fluency (1 to 5). "
              "The rater is to be named before the sheet is filled in. No rating has been "
              "made. Hausa, Igbo and Pidgin dialogue quality is unverified.", ""]
    lines += ["## Language detection", ""]
    if det:
        lines += ["| Language | Sentences | Accuracy |", "|---|---|---|",
                  *[f"| {k} | {v['n']} | {v['accuracy']:.2f} |" for k, v in det.items()], ""]
    else:
        lines += ["not run", ""]
    lines += ["## Speech round trip (text to speech to text, about 10 s per language)", ""]
    if rt:
        lines += ["| Locale | Voice | Seconds | WER | chrF |", "|---|---|---|---|---|",
                  *[f"| {k} | {v['voice']} | {v['seconds']} | {v['wer']:.2f} | {v['chrf']:.1f} |"
                    for k, v in rt.items()], "",
                  "STT: faster-whisper small (en, pcm), MMS-1b-all adapters (yo, ha, ig). "
                  "Pidgin uses the English voice and the English Whisper language.", ""]
    else:
        lines += ["not run", ""]
    lines += ["## Embedding and re-ranker hosts", "", "not run" if not hosts else
              "```\n" + json.dumps(hosts, indent=1) + "\n```", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--src", type=Path, default=common.OUT)
    args = parser.parse_args(argv)
    (HERE / "REPORT.md").write_text(build(args.src), encoding="utf-8")
    print(f"wrote {HERE / 'REPORT.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
