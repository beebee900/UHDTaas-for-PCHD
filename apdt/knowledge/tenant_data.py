"""Synthetic tenant data: stock, test prices and staff rotas (design 06, 6.3.1).

These are tenant data, not clinical knowledge, so they carry no source. They are generated
from a fixed seed so every run of the demo sees the same facilities:

- `kb/stock/<tenant>.csv`: units on hand per drug (ATC) that a regimen in the kb uses
- `kb/prices/<tenant>.csv`: price in naira and turnaround in hours per kb test
- `kb/rota/<tenant>.yaml`: on-call staff per role and shift, with escalation order
"""

from __future__ import annotations

import csv
import random
from collections.abc import Iterator, Mapping
from pathlib import Path
from typing import Any

import yaml

from atra.config import ROOT
from atra.kb import KnowledgeBase

# Tenant → (service tier, share of drugs stocked, price multiplier, staff per role).
TENANTS: Mapping[str, tuple[str, float, float, Mapping[str, int]]] = {
    "fac-a": ("specialist", 0.95, 1.3, {"medical_officer": 4, "nurse": 8, "radiologist": 1,
                                         "pharmacist": 2, "lab_scientist": 2}),
    "fac-b": ("facility", 0.7, 1.0, {"medical_officer": 1, "nurse": 3, "community_health_worker": 2,
                                      "pharmacist": 1}),
}
# Tests a primary health centre runs on site; everything else is referred out.
PHC_TESTS = ("test.malaria_rdt", "test.malaria_microscopy", "test.haemoglobin", "test.glucose",
             "test.urine_dipstick", "test.urine_ketones", "test.hiv_rapid", "test.typhoid_rdt")
SHIFTS = ("day", "night")
ESCALATION = ("community_health_worker", "nurse", "medical_officer")
SEED = 20261007


def _atc(obj: Any) -> Iterator[tuple[str, str]]:
    if isinstance(obj, Mapping):
        if isinstance(obj.get("atc"), str):
            yield obj["atc"], str(obj.get("drug", obj["atc"]))
        for v in obj.values():
            yield from _atc(v)
    elif isinstance(obj, list):
        for v in obj:
            yield from _atc(v)


def drugs(kb: KnowledgeBase) -> dict[str, str]:
    out: dict[str, str] = {}
    for eid in kb.ids():
        if eid.startswith("dose."):
            for code, name in _atc(kb.entry(eid).content()):
                out.setdefault(code, name)
    return dict(sorted(out.items()))


def tests(kb: KnowledgeBase) -> list[str]:
    return [eid for eid in kb.ids() if eid.startswith("test.")]


def write(kb_dir: Path = ROOT / "kb") -> list[Path]:
    kb = KnowledgeBase(kb_dir)
    written: list[Path] = []
    for tenant, (tier, stocked, price_x, staff) in TENANTS.items():
        rng = random.Random(f"{SEED}:{tenant}")
        stock = kb_dir / "stock" / f"{tenant}.csv"
        stock.parent.mkdir(exist_ok=True)
        with stock.open("w", newline="") as fh:
            w = csv.writer(fh, lineterminator="\n")
            w.writerow(("atc", "drug", "units_on_hand", "reorder_level"))
            for code, name in drugs(kb).items():
                units = rng.randint(20, 400) if rng.random() < stocked else 0
                w.writerow((code, name, units, 30))
        prices = kb_dir / "prices" / f"{tenant}.csv"
        prices.parent.mkdir(exist_ok=True)
        with prices.open("w", newline="") as fh:
            w = csv.writer(fh, lineterminator="\n")
            w.writerow(("test", "on_site", "price_ngn", "turnaround_h"))
            for tid in tests(kb):
                on_site = tier == "specialist" or tid.startswith(PHC_TESTS)
                price = round(rng.randint(15, 250) * 100 * price_x, -2)
                hours = rng.choice((1, 2, 4, 24)) if on_site else rng.choice((48, 72))
                w.writerow((tid, on_site, int(price), hours))
        roster: list[dict[str, Any]] = []
        for role, n in staff.items():
            for i in range(1, n + 1):
                roster.append({"staff_id": f"{tenant}-{role}-{i}", "role": role,
                               "shift": SHIFTS[(i - 1) % 2], "contact": "sms+app"})
        rota = kb_dir / "rota" / f"{tenant}.yaml"
        rota.parent.mkdir(exist_ok=True)
        rota.write_text(
            f"# Synthetic staff rota for {tenant} ({tier}); generated by "
            "`python -m apdt.knowledge.sourcing tenant-data`.\n"
            + yaml.safe_dump({"tenant": tenant, "tier": tier,
                              "escalation_order": [r for r in ESCALATION if r in staff],
                              "staff": roster}, sort_keys=False))
        written += [stock, prices, rota]
    return written
